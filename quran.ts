export interface QuranItem {
  url: string;
  title: string;
}

export interface QuranTarget {
  type: "ayah" | "surah" | "range";
  surah: number;
  surahName: string;
  totalVerses?: number;
  ayah?: number;
  startAyah?: number;
  endAyah?: number;
  title: string;
  items: QuranItem[];
}

export type ParseResult =
  | { success: true; target: QuranTarget }
  | { success: false; error: string };

const norm = (s: string) =>
  s.toLowerCase().replace(/^(al|an|at|ar|as|az|ad)-/i, "").replace(/[^a-z0-9]/g, "");

function resolveChapter(input: string): ChapterInfo | null {
  const trimmed = input.trim();
  if (/^\d+$/.test(trimmed)) {
    const id = parseInt(trimmed, 10);
    return id >= 1 && id <= 114 ? CHAPTERS[id - 1] : null;
  }
  const n = norm(trimmed);
  if (!n) return null;
  return (
    CHAPTERS.find((c) => norm(c.name) === n) ||
    CHAPTERS.find((c) => norm(c.name).includes(n)) ||
    null
  );
}

export function parseQuranQuery(query: string): ParseResult {
  const trimmed = query.trim();
  const colonIdx = trimmed.indexOf(":");

  if (colonIdx !== -1) {
    const rawSurah = trimmed.slice(0, colonIdx).trim();
    const rawAyah = trimmed.slice(colonIdx + 1).trim();
    const chapter = resolveChapter(rawSurah);

    if (!chapter) {
      return { success: false, error: `Invalid surah "${rawSurah}". Please enter a surah 1-114.` };
    }

    // Range: e.g. "3-6" or "3 - 6"
    const rangeMatch = rawAyah.match(/^(\d{1,3})\s*-\s*(\d{1,3})$/);
    if (rangeMatch) {
      const startAyah = parseInt(rangeMatch[1], 10);
      const endAyah = parseInt(rangeMatch[2], 10);

      if (startAyah < 1 || startAyah > chapter.verses) {
        return {
          success: false,
          error: `Surah ${chapter.name} only has ${chapter.verses} ayahs (invalid start ayah ${startAyah}).`,
        };
      }

      if (endAyah < 1 || endAyah > chapter.verses) {
        return {
          success: false,
          error: `Surah ${chapter.name} only has ${chapter.verses} ayahs (invalid end ayah ${endAyah}).`,
        };
      }

      if (startAyah > endAyah) {
        return {
          success: false,
          error: `Start ayah (${startAyah}) must be less than or equal to end ayah (${endAyah}).`,
        };
      }

      const sPad = String(chapter.id).padStart(3, "0");
      const items: QuranItem[] = [];

      // Prepend Bismillah when starting from ayah 1 (except Al-Fatihah which has it as 1:1, and At-Tawbah which has none)
      if (startAyah === 1 && chapter.id !== 1 && chapter.id !== 9) {
        items.push({
          url: "https://everyayah.com/data/Alafasy_128kbps/001001.mp3",
          title: "Bismillah ir-Rahman ir-Rahim",
        });
      }

      for (let a = startAyah; a <= endAyah; a++) {
        const aPad = String(a).padStart(3, "0");
        items.push({
          url: `https://everyayah.com/data/Alafasy_128kbps/${sPad}${aPad}.mp3`,
          title: `Surah ${chapter.name} [${chapter.id}:${a}]`,
        });
      }

      const title =
        startAyah === endAyah
          ? `Surah ${chapter.name} [${chapter.id}:${startAyah}]`
          : `Surah ${chapter.name} [${chapter.id}:${startAyah}-${endAyah}]`;

      return {
        success: true,
        target: {
          type: startAyah === endAyah ? "ayah" : "range",
          surah: chapter.id,
          surahName: chapter.name,
          startAyah,
          endAyah,
          title,
          items,
        },
      };
    }

    // Single Ayah: e.g. "34"
    const ayah = parseInt(rawAyah, 10);
    if (isNaN(ayah) || ayah < 1 || ayah > chapter.verses) {
      return {
        success: false,
        error: `Surah ${chapter.name} only has ${chapter.verses} ayahs (requested ayah ${rawAyah}).`,
      };
    }

    const sPad = String(chapter.id).padStart(3, "0");
    const aPad = String(ayah).padStart(3, "0");
    const title = `Surah ${chapter.name} [${chapter.id}:${ayah}]`;

    const items: QuranItem[] = [];
    if (ayah === 1 && chapter.id !== 1 && chapter.id !== 9) {
      items.push({
        url: "https://everyayah.com/data/Alafasy_128kbps/001001.mp3",
        title: "Bismillah ir-Rahman ir-Rahim",
      });
    }
    items.push({
      url: `https://everyayah.com/data/Alafasy_128kbps/${sPad}${aPad}.mp3`,
      title,
    });

    return {
      success: true,
      target: {
        type: "ayah",
        surah: chapter.id,
        surahName: chapter.name,
        ayah,
        title,
        items,
      },
    };
  }

  const chapter = resolveChapter(trimmed);
  if (!chapter) {
    return {
      success: false,
      error: `Invalid input "${trimmed}". Use "/quran-play 2" for a full surah, "/quran-play 2:34" for an ayah, or "/quran-play 2:3-6" for a range.`,
    };
  }

  const sPad = String(chapter.id).padStart(3, "0");
  const url = `https://cdn.mp3quran.net/audio/mishary-alafasy/r1/${sPad}.mp3`;
  const title = `Surah ${chapter.name} (Full Surah - ${chapter.verses} Ayahs)`;

  return {
    success: true,
    target: {
      type: "surah",
      surah: chapter.id,
      surahName: chapter.name,
      totalVerses: chapter.verses,
      title,
      items: [{ url, title }],
    },
  };
}
